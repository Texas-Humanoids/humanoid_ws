#!/usr/bin/env python3
"""Convert urdf/walker_v2.urdf into the MuJoCo model used by th_sim.

    python3 scripts/urdf_to_mjcf.py   # from src/th_description/robots/walker_v2

Writes mjcf/walker_v2.xml (robot only) next to the hand-written mjcf/scene.xml
(floor, light). What the conversion adds to the plain URDF import:

- a freejoint on base_link and an `imu` site at the URDF imu_link (identity);
- joint armature from isaaclab walker_v2_cfg.py (RS03 0.015, RS06 0.008, RS02 0.004);
- one torque `motor` actuator per joint, ctrlrange = the URDF effort (peak torque);
- collision boxes in class `collision` (contype 2, conaffinity 1): they touch the
  floor but not each other, because the boxes overlap (self-collision OFF, as in
  training); meshes are visual only (group 2, no contacts, no mass).
"""

import os
import re
import tempfile
import xml.etree.ElementTree as ET

import mujoco

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URDF = os.path.join(HERE, 'urdf', 'walker_v2.urdf')
OUT = os.path.join(HERE, 'mjcf', 'walker_v2.xml')

ARMATURE = {'hip_pitch': 0.015, 'hip_roll': 0.015, 'knee_pitch': 0.015,
            'hip_yaw': 0.004, 'ankle_pitch': 0.008}


def convert():
    with open(URDF) as f:
        urdf = f.read()
    urdf = urdf.replace('package://walker_v2/meshes/', '')
    urdf = urdf.replace(
        '<robot name="walker_v2">',
        '<robot name="walker_v2"><mujoco><compiler meshdir="%s" discardvisual="false" '
        'balanceinertia="true" fusestatic="false"/></mujoco>' % os.path.join(HERE, 'meshes'), 1)
    with tempfile.NamedTemporaryFile('w', suffix='.urdf', delete=False) as tmp:
        tmp.write(urdf)
    try:
        model = mujoco.MjModel.from_xml_path(tmp.name)
    finally:
        os.unlink(tmp.name)
    with tempfile.NamedTemporaryFile('r', suffix='.xml', delete=False) as tmp:
        mujoco.mj_saveLastXML(tmp.name, model)
        root = ET.parse(tmp.name).getroot()
    os.unlink(tmp.name)

    efforts = dict(re.findall(
        r'<joint name="(\w+)" type="revolute">.*?effort="([\d.]+)"', urdf, re.S))

    root.find('compiler').attrib = {
        'angle': 'radian', 'meshdir': '../meshes', 'autolimits': 'true'}
    worldbody = root.find('worldbody')
    # Ready pose (README: base height 0.659 m) plus 1 cm, like the Isaac Lab init_state.
    base = worldbody.find("body[@name='base_link']")
    base.set('pos', '0 0 0.67')
    base.insert(0, ET.Element('freejoint', {'name': 'floating_base'}))
    # The fixed imu_link body (identity in the URDF) carries the IMU site.
    imu = base.find("body[@name='imu_link']")
    ET.SubElement(imu, 'site', {'name': 'imu', 'size': '0.01'})

    for geom in root.iter('geom'):
        for key in ('contype', 'conaffinity', 'group', 'density', 'rgba'):
            geom.attrib.pop(key, None)
        geom.set('class', 'visual' if geom.get('type') == 'mesh' else 'collision')
    default = ET.Element('default')
    root.insert(1, default)
    ET.SubElement(ET.SubElement(default, 'default', {'class': 'visual'}), 'geom', {
        'contype': '0', 'conaffinity': '0', 'group': '2', 'density': '0',
        'rgba': '0.25 0.25 0.27 1'})
    ET.SubElement(ET.SubElement(default, 'default', {'class': 'collision'}), 'geom', {
        'contype': '2', 'conaffinity': '1', 'group': '3', 'rgba': '0.8 0.4 0.2 0.4'})

    for joint in root.iter('joint'):
        short = joint.get('name').split('_', 1)[1].removesuffix('_joint')
        joint.set('armature', str(ARMATURE[short]))
        joint.attrib.pop('actuatorfrcrange', None)

    actuator = ET.SubElement(root, 'actuator')
    for joint in root.iter('joint'):
        limit = efforts[joint.get('name')]
        ET.SubElement(actuator, 'motor', {
            'name': joint.get('name').removesuffix('_joint'), 'joint': joint.get('name'),
            'ctrlrange': f'-{limit} {limit}'})
    sensor = ET.SubElement(root, 'sensor')
    ET.SubElement(sensor, 'framequat', {'name': 'imu_quat', 'objtype': 'site', 'objname': 'imu'})
    ET.SubElement(sensor, 'gyro', {'name': 'imu_gyro', 'site': 'imu'})
    ET.SubElement(sensor, 'accelerometer', {'name': 'imu_acc', 'site': 'imu'})

    ET.indent(root)
    with open(OUT, 'w') as f:
        f.write('<!-- Generated by scripts/urdf_to_mjcf.py from urdf/walker_v2.urdf. '
                'Do not edit; rerun the script. -->\n')
        f.write(ET.tostring(root, encoding='unicode'))
        f.write('\n')
    # Check it loads with the scene.
    model = mujoco.MjModel.from_xml_path(os.path.join(HERE, 'mjcf', 'scene.xml'))
    print(f'wrote {OUT}: nq={model.nq} nu={model.nu} '
          f'mass={sum(model.body_mass):.2f} kg')


if __name__ == '__main__':
    convert()
